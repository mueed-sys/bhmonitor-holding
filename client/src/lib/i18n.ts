export function t(key: string, lang: Lang): string {
  return translations[key]?.[lang] || translations[key]?.en || key;
}

interface LangContextType {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: (key: string) => string;
  isRtl: boolean;
}

export const LangContext = createContext<LangContextType>({
  lang: "en",
  setLang: () => {},
  t: (key: string) => key,
  isRtl: false,
});

export function useLangProvider() {
  const stored = typeof window !== "undefined" ? (localStorage.getItem("bhmonitor-lang") as Lang) : "en";
  const [lang, setLangState] = useState<Lang>(stored || "en");

  useEffect(() => {
    document.documentElement.dir = lang === "ar" ? "rtl" : "ltr";
    document.documentElement.lang = lang;
  }, [lang]);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    localStorage.setItem("bhmonitor-lang", l);
  }, []);

  const translate = useCallback((key: string) => t(key, lang), [lang]);

  return { lang, setLang, t: translate, isRtl: lang === "ar" };
}

export function useLang(): LangContextType {
  return useContext(LangContext);
}
